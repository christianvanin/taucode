"""
init_skill.py - Initializes the modular structure for a new Antigravity / TauCode IDE skill.
Supports archetypes (workflow, tool-wrapper, reviewer, minimal), category folders,
and standard Antigravity directories (scripts, references, examples, resources).
Zero external dependencies (standard Python library only).
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path

VALID_ARCHETYPES = ["workflow", "tool-wrapper", "reviewer", "minimal"]
DEFAULT_FOLDERS = ["General", "Tools", "Development", "DevOps", "Automation", "AI"]


def is_valid_skill_name(name: str) -> bool:
    """Verifies that the skill name is valid kebab-case (lowercase letters, numbers, hyphens)."""
    return bool(re.match(r"^[a-z0-9]+(-[a-z0-9]+)*$", name))


def find_workspace_root() -> Path:
    """Finds the workspace root directory containing .git or .agents."""
    curr = Path.cwd().resolve()
    for parent in [curr] + list(curr.parents):
        if (parent / ".git").exists() or (parent / ".agents").exists() or (parent / "_agents").exists():
            return parent
    return curr


def resolve_target_dir(name: str, scope: str, custom_path: str = None) -> Path:
    """Resolves destination path based on target scope and TauCode IDE conventions."""
    if custom_path:
        base = Path(custom_path).resolve()
        return base if base.name == name else base / name

    home = Path.home()

    if scope == "builtin":
        # Native TauCode IDE built-in skills directory
        return home / ".gemini" / "antigravity" / "builtin" / "skills" / name

    if scope == "global":
        # Global user configuration skills
        return home / ".gemini" / "config" / "skills" / name

    if scope == "workspace":
        root = find_workspace_root()
        if (root / "_agents").exists():
            return root / "_agents" / "skills" / name
        elif (root / ".agent").exists():
            return root / ".agent" / "skills" / name
        else:
            return root / ".agents" / "skills" / name

    # Local directory ./<name>
    return Path.cwd() / name


def generate_frontmatter_description(name: str, archetype: str, custom_desc: str = "") -> str:
    """Generates an activation-ready description conforming to the 9-point trigger score."""
    if custom_desc.strip():
        desc = custom_desc.strip()
        if not any(w in desc.lower() for w in ["use when", "use whenever", "use for", "usa quando"]):
            desc += f' Use when the user asks to manage, run, or verify "{name}".'
        return desc

    title = name.replace("-", " ")
    if archetype == "workflow":
        return (
            f"Executes and coordinates the end-to-end workflow for {title}. "
            f'Use whenever the user asks to "run {title}", "execute {name} procedure", '
            f'"update {title}", or complete this multi-step operational task. '
            f'Do NOT use for one-off throwaway commands.'
        )
    elif archetype == "tool-wrapper":
        return (
            f"Interfaces with and runs deterministic CLI tools for {title}. "
            f'Use when the user asks to "analyze {title}", "run {name} check", '
            f'"scan with {name}", or request automated reports generated by dedicated scripts. '
            f'Do NOT use for ad-hoc manual scripting.'
        )
    elif archetype == "reviewer":
        return (
            f"Analyzes, reviews, and audits code or architecture related to {title}. "
            f'Use when the user asks to "review {title}", "audit {name}", '
            f'"check changes for {title}", or request compliance and best-practice inspection. '
            f'Do NOT use for generic text grammar checks.'
        )
    else:  # minimal
        return (
            f"Operational runbook for {title}. "
            f'Use when the user asks to "manage {name}", "configure {title}", '
            f'or perform related setup operations.'
        )


