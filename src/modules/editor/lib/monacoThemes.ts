const registeredInstances = new WeakSet<object>();

/** Call this to register all custom themes into the given Monaco instance. */
export function registerMonacoThemes(
  monaco: typeof import("monaco-editor"),
): void {
  if (!monaco?.editor?.defineTheme) return;
  if (registeredInstances.has(monaco.editor)) return;
  registeredInstances.add(monaco.editor);
  for (const [id, palette] of Object.entries(PALETTES)) {
    monaco.editor.defineTheme(id, buildThemeData(id, palette as Palette));
  }
}

/** The Monaco theme name that corresponds to the given EditorThemeId. */
export function monacoThemeId(id: EditorThemeId): string {
  return id;
}
