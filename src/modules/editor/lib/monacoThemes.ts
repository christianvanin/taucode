/**
 * Monaco Editor theme definitions — mirrors the CodeMirror palette list.
 * Every theme maps directly to the colours defined in cmThemes.ts so the
 * editor always matches the rest of the UI's chosen palette.
 */
import type { EditorThemeId } from "@/modules/settings/store";
import type * as Monaco from "monaco-editor";

type Palette = {
  mode: "light" | "dark";
  bg: string;
  fg: string;
  caret: string;
  selection: string;
  lineHighlight: string;
  gutterFg: string;
  comment: string;
  keyword: string;
  string: string;
  number: string;
  constant: string;
  func: string;
  variable: string;
  property: string;
  type: string;
  operator: string;
  tag: string;
  attr: string;
  heading: string;
  link: string;
  invalid: string;
};

function buildThemeData(
  _id: string,
  p: Palette,
): Monaco.editor.IStandaloneThemeData {
  const base: Monaco.editor.BuiltinTheme = p.mode === "dark" ? "vs-dark" : "vs";
  return {
    base,
    inherit: true,
    rules: [
      { token: "", foreground: p.fg.replace("#", "") },
      {
        token: "comment",
        foreground: p.comment.replace("#", ""),
        fontStyle: "italic",
      },
      {
        token: "comment.line",
        foreground: p.comment.replace("#", ""),
        fontStyle: "italic",
      },
      {
        token: "comment.block",
        foreground: p.comment.replace("#", ""),
        fontStyle: "italic",
      },
      { token: "keyword", foreground: p.keyword.replace("#", "") },
      { token: "keyword.control", foreground: p.keyword.replace("#", "") },
      { token: "keyword.operator", foreground: p.keyword.replace("#", "") },
      { token: "keyword.other", foreground: p.keyword.replace("#", "") },
      { token: "storage", foreground: p.keyword.replace("#", "") },
      { token: "storage.type", foreground: p.keyword.replace("#", "") },
      { token: "string", foreground: p.string.replace("#", "") },
      { token: "string.quoted", foreground: p.string.replace("#", "") },
      { token: "string.template", foreground: p.string.replace("#", "") },
      { token: "string.regexp", foreground: p.string.replace("#", "") },
      { token: "regexp", foreground: p.string.replace("#", "") },
      { token: "number", foreground: p.number.replace("#", "") },
      { token: "number.hex", foreground: p.number.replace("#", "") },
      { token: "number.float", foreground: p.number.replace("#", "") },
      { token: "constant", foreground: p.constant.replace("#", "") },
      { token: "constant.language", foreground: p.constant.replace("#", "") },
      { token: "constant.numeric", foreground: p.number.replace("#", "") },
      { token: "entity.name.function", foreground: p.func.replace("#", "") },
      { token: "support.function", foreground: p.func.replace("#", "") },
      { token: "function", foreground: p.func.replace("#", "") },
      { token: "variable", foreground: p.variable.replace("#", "") },
      {
        token: "variable.parameter",
        foreground: p.variable.replace("#", ""),
      },
      { token: "variable.other", foreground: p.variable.replace("#", "") },
      { token: "support.variable", foreground: p.variable.replace("#", "") },
      { token: "entity.name.type", foreground: p.type.replace("#", "") },
      { token: "entity.name.class", foreground: p.type.replace("#", "") },
      { token: "support.class", foreground: p.type.replace("#", "") },
      { token: "support.type", foreground: p.type.replace("#", "") },
      { token: "entity.other.inherited-class", foreground: p.type.replace("#", "") },
      { token: "type", foreground: p.type.replace("#", "") },
      { token: "operator", foreground: p.operator.replace("#", "") },
      { token: "punctuation", foreground: p.operator.replace("#", "") },
      { token: "delimiter", foreground: p.operator.replace("#", "") },
      { token: "delimiter.bracket", foreground: p.operator.replace("#", "") },
      { token: "delimiter.parenthesis", foreground: p.operator.replace("#", "") },
      { token: "delimiter.square", foreground: p.operator.replace("#", "") },
      { token: "tag", foreground: p.tag.replace("#", "") },
      { token: "tag.html", foreground: p.tag.replace("#", "") },
      { token: "metatag", foreground: p.tag.replace("#", "") },
      { token: "attribute.name", foreground: p.attr.replace("#", "") },
      { token: "attribute.value", foreground: p.string.replace("#", "") },
      { token: "entity.name.tag", foreground: p.tag.replace("#", "") },
      { token: "entity.other.attribute-name", foreground: p.attr.replace("#", "") },
      // Markdown
      {
        token: "markup.heading",
        foreground: p.heading.replace("#", ""),
        fontStyle: "bold",
      },
      { token: "markup.underline.link", foreground: p.link.replace("#", "") },
      { token: "markup.italic", foreground: p.fg.replace("#", ""), fontStyle: "italic" },
      { token: "markup.bold", foreground: p.fg.replace("#", ""), fontStyle: "bold" },
      { token: "markup.raw", foreground: p.string.replace("#", "") },
      { token: "markup.quote", foreground: p.comment.replace("#", ""), fontStyle: "italic" },
      // Properties / members
      { token: "variable.other.property", foreground: p.property.replace("#", "") },
      { token: "support.other.variable", foreground: p.property.replace("#", "") },
      { token: "meta.property-name", foreground: p.property.replace("#", "") },
      // Invalid
      { token: "invalid", foreground: p.invalid.replace("#", "") },
      { token: "invalid.illegal", foreground: p.invalid.replace("#", "") },
    ],
    colors: {
      "editor.background": p.bg,
      "editor.foreground": p.fg,
      "editorCursor.foreground": p.caret,
      "editor.lineHighlightBackground": p.lineHighlight,
      "editor.lineHighlightBorder": "#00000000",
      "editor.selectionBackground": p.selection,
      "editor.inactiveSelectionBackground":
        p.selection + (p.mode === "dark" ? "88" : "bb"),
      "editorLineNumber.foreground": p.gutterFg,
      "editorLineNumber.activeForeground": p.fg,
      "editorGutter.background": p.bg,
      "editorIndentGuide.background1":
        p.gutterFg + (p.mode === "dark" ? "33" : "44"),
      "editorIndentGuide.activeBackground1":
        p.gutterFg + (p.mode === "dark" ? "77" : "88"),
      "editorWhitespace.foreground": `${p.gutterFg}44`,
      "editorWidget.background": p.lineHighlight,
      "editorWidget.border": `${p.gutterFg}${p.mode === "dark" ? "44" : "33"}`,
      "editorWidget.foreground": p.fg,
      "input.background": p.bg,
      "input.foreground": p.fg,
      "input.border": `${p.gutterFg}${p.mode === "dark" ? "55" : "44"}`,
      "input.placeholderForeground": `${p.gutterFg}99`,
      "inputOption.activeBackground": p.selection,
      "inputOption.activeBorder": p.keyword,
      "inputOption.activeForeground": p.fg,
      "editorSuggestWidget.background": p.lineHighlight,
      "editorSuggestWidget.border": `${p.gutterFg}${p.mode === "dark" ? "44" : "33"}`,
      "editorSuggestWidget.foreground": p.fg,
      "editorSuggestWidget.selectedBackground": p.selection,
      "editorSuggestWidget.highlightForeground": p.keyword,
      "editorHoverWidget.background": p.bg,
      "editorHoverWidget.border": `${p.gutterFg}${p.mode === "dark" ? "33" : "22"}`,
      "editorHoverWidget.foreground": p.fg,
      "editorHoverWidget.statusBarBackground": p.lineHighlight,
      "editorHoverWidget.highlightForeground": p.func,
      "editorInfo.foreground": p.func,
      "editorWarning.foreground": p.number,
      "editorError.foreground": p.invalid,
      "editorBracketMatch.background": p.selection,
      "editorBracketMatch.border": `${p.keyword}66`,
      "editorOverviewRuler.border": "#00000000",
      "scrollbar.shadow": "#00000000",
      "scrollbarSlider.background": `${p.gutterFg}${p.mode === "dark" ? "44" : "33"}`,
      "scrollbarSlider.hoverBackground": `${p.gutterFg}${p.mode === "dark" ? "77" : "66"}`,
      "scrollbarSlider.activeBackground": `${p.gutterFg}${p.mode === "dark" ? "aa" : "99"}`,
      "editorFindMatch.background": `${p.number}55`,
      "editorFindMatchHighlight.background": `${p.number}33`,
      "editorFindMatchBorder": `${p.number}99`,
      // Minimap
      "minimap.background": "#00000000",
      "minimapSlider.background": `${p.gutterFg}${p.mode === "dark" ? "44" : "33"}`,
    },
  };
}

